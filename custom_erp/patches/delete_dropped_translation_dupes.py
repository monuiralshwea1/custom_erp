def execute():
    removed = 0
    for i in range(0, len(SOURCES), 500):
        chunk = SOURCES[i:i + 500]
        placeholders = ", ".join(["%s"] * len(chunk))
        rows = frappe.db.sql(
            f"select name from `tabTranslation` where TRIM(source_text) in ({placeholders})",
            tuple(chunk),
        )
        for (n,) in rows:
            frappe.db.delete("Translation", n)
            removed += 1
    frappe.db.commit()
    print(f"[tr-cleanup] removed {removed} stale translation docs")
